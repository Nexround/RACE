"""Utilities for generating a thin subclass wrapper around a perturbed model.

When ``mean_ablation`` folds mean contributions into bias terms on MLP
``down_proj`` layers, the architecture needs to support those biases at
load-time.  Rather than patching the original ``modeling_*.py`` source
(fragile, version-sensitive), we generate a self-contained Python module
alongside the checkpoint that:

1. Defines a replacement **MLP class** that overrides ``down_proj``
   construction to honour a ``mlp_bias`` config flag.
2. Defines a thin **base model subclass** (e.g. ``RacePerturbedQwen3Model``)
   that sets ``_supports_attention_backend = True`` so vLLM's Transformers
   modeling backend can load the custom model without falling back to a
   warning path.
3. Defines a thin **ForCausalLM subclass** (e.g.
   ``RacePerturbedQwen3ForCausalLM``) whose ``__init__`` swaps out all
   original MLP instances with instances of the replacement class and
   copies the (already-modified) weights in.
4. Sets ``config.json``'s ``auto_map`` / ``architectures`` fields so that
   ``AutoModelForCausalLM.from_pretrained(..., trust_remote_code=True)``
   resolves to the subclass automatically, and also adds an ``AutoModel``
   entry (required by the vLLM Transformers modeling backend).

The generated file is written to ``<save_path>/modeling_race_perturbed.py``
and imports the *original* modeling classes from ``transformers`` directly,
so it has zero dependencies on the RACE package at inference time.

vLLM compatibility
~~~~~~~~~~~~~~~~~~
vLLM's Transformers modeling backend discovers custom models through
``config.json``'s ``auto_map`` field.  It requires:

* ``auto_map["AutoModel"]`` — points at the *base* model class (not the
  causal-LM wrapper).  The base class must have
  ``_supports_attention_backend = True``.
* ``auto_map["AutoModelForCausalLM"]`` — points at the causal-LM wrapper.

Both entries are written by :func:`materialize_race_perturbed_class`.
"""

from __future__ import annotations

import logging
import os
from typing import Optional

import torch

logger = logging.getLogger(__name__)


# ---------------------------------------------------------------------------
# Internal helpers
# ---------------------------------------------------------------------------


def _get_mlp_class_name(model: torch.nn.Module) -> Optional[str]:
    """Return the class name of the first MLP sub-module found in a model."""
    from race.llm.model_utils import get_decoder_layers, get_language_model

    try:
        lm = get_language_model(model)
        layers = list(get_decoder_layers(lm))
    except AttributeError:
        return None

    for layer in layers:
        mlp = getattr(layer, "mlp", None)
        if mlp is not None:
            return type(mlp).__name__
    return None


def _get_base_model_class_name(model: torch.nn.Module) -> Optional[str]:
    """Return the class name of the inner backbone model (e.g. ``Qwen3Model``).

    HuggingFace causal-LM wrappers (``XxxForCausalLM``) store the backbone
    under ``self.model`` (most architectures) or ``self.transformer`` / other
    names.  We look for the first direct child whose class name ends with
    ``"Model"`` or who has a ``layers`` attribute, which is how the backbone
    is identified by the model-introspection utilities.
    """
    # Try common attribute names in priority order
    for attr in ("model", "transformer", "backbone"):
        candidate = getattr(model, attr, None)
        if candidate is not None and hasattr(candidate, "layers"):
            return type(candidate).__name__

    # Fallback: walk direct children
    for child in model.children():
        if hasattr(child, "layers"):
            return type(child).__name__

    # Last resort: derive from the ForCausalLM class name heuristically
    causal_lm_name = type(model).__name__
    # e.g. "Qwen3ForCausalLM" → try "Qwen3Model"
    prefix = causal_lm_name.replace("ForCausalLM", "").replace("CausalLM", "")
    return f"{prefix}Model"


def _get_modeling_module_name(model: torch.nn.Module) -> str:
    """Return the dotted module name where the causal LM class lives."""
    cls = type(model)
    return cls.__module__


# ---------------------------------------------------------------------------
# Code-generation
# ---------------------------------------------------------------------------

_PERTURBED_MODULE_TEMPLATE = '''\
"""Auto-generated by RACE: thin subclass of {base_causal_lm_class} with mlp_bias support.

This file is produced by ``race_eval.llm.perturbed_model.materialize_race_perturbed_class``
and is placed next to the checkpoint so that::

    AutoModelForCausalLM.from_pretrained(path, trust_remote_code=True)

resolves to ``{wrapper_class_name}``.

The subclass replaces every ``{mlp_class_name}`` instance in the loaded model
with ``RacePerturbedMLP``, which re-constructs ``down_proj`` with
``bias=config.mlp_bias`` (defaulting to ``False`` when absent). The modified
weight tensors (and any bias terms folded in
by the mean-ablation surgery) are copied from the parent checkpoint weights
directly — no recomputation is required.

vLLM Transformers modeling backend
~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
``{base_model_class}`` sets ``_supports_attention_backend = True`` which
allows vLLM to route attention calls through its own CUDA kernels instead of
the plain PyTorch implementation.  ``config.json``'s ``auto_map`` contains
both an ``AutoModel`` entry (pointing here) and an ``AutoModelForCausalLM``
entry, which is what the vLLM Transformers backend requires to discover and
load this custom architecture.
"""
from __future__ import annotations

import torch.nn as nn
from {modeling_import} import {base_causal_lm_class}, {base_model_class}, {mlp_class_name}
{config_import_line}


class RacePerturbedMLP({mlp_class_name}):
    """Drop-in replacement for ``{mlp_class_name}`` that supports ``config.mlp_bias``.

    When ``config.mlp_bias`` is ``True`` the parent's ``down_proj`` (built
    without bias) is replaced with a biased ``nn.Linear``.  This makes the
    module's parameter layout match the saved state dict, which carries a
    ``down_proj.bias`` tensor for every ablated layer.
    """

    def __init__(self, config):
        # Initialize the parent with an unbiased down projection.
        super().__init__(config)
        if getattr(config, "mlp_bias", False) and self.down_proj.bias is None:
            # Re-create down_proj with bias so the state-dict slot is present.
            self.down_proj = nn.Linear(
                self.down_proj.in_features,
                self.down_proj.out_features,
                bias=True,
            )


class {base_model_wrapper_class}({base_model_class}):
    """RACE-perturbed base model — identical to ``{base_model_class}`` but
    declares ``_supports_attention_backend = True`` so that vLLM's Transformers
    modeling backend can load this custom architecture and use its own attention
    CUDA kernels instead of the plain PyTorch fallback.

    When ``config.mlp_bias`` is ``True``, ``__init__`` also replaces every
    ``{mlp_class_name}`` instance with :class:`RacePerturbedMLP` so that
    ``down_proj`` carries a bias parameter.  This is critical for the vLLM
    Transformers backend which creates the model via
    ``AutoModel.from_config`` (not ``AutoModelForCausalLM``) and then decides
    whether each ``RowParallelLinear`` needs a bias by inspecting the
    ``nn.Linear`` it replaces — if ``down_proj.bias`` is ``None`` at that
    point, the parallel linear is built without bias and the checkpoint's
    ``down_proj.bias`` tensor has nowhere to land, causing a ``ValueError``.

    This class is referenced by ``auto_map["AutoModel"]`` in ``config.json``.
    """

    # Required by the vLLM Transformers modeling backend.
    # See: vLLM docs — Writing custom models.
    _supports_attention_backend = True

    _auto_class = "AutoModel"

    def __init__(self, config):
        super().__init__(config)
        if getattr(config, "mlp_bias", False):
            self._replace_mlp_modules(config)

    def _replace_mlp_modules(self, config) -> None:
        """Swap original MLP instances for RacePerturbedMLP instances.

        Unlike the CausalLM wrapper (which must locate the inner backbone via
        ``self.model`` / ``self.transformer``), the base model *is* the
        backbone, so ``self.layers`` is accessed directly.
        """
        decoder_layers = getattr(self, "layers", None)
        if decoder_layers is None:
            return
        for layer in decoder_layers:
            mlp = getattr(layer, "mlp", None)
            if mlp is None or not isinstance(mlp, {mlp_class_name}):
                continue
            new_mlp = RacePerturbedMLP(config)
            new_mlp.load_state_dict(mlp.state_dict(), strict=False)
            layer.mlp = new_mlp


class {wrapper_class_name}({base_causal_lm_class}):
    """RACE-perturbed causal LM — identical numerics, mlp_bias support.

    When loaded via ``from_pretrained`` the base class reads the safetensors
    shards.  If ``config.mlp_bias`` is ``True`` this class replaces all MLP
    instances with :class:`RacePerturbedMLP` *before* the weights are loaded
    so that the state-dict keys and tensor shapes match the biased variant.
    """

    config_class = {config_class_expr}

    # Tell transformers that this subclass should be used when model_type
    # matches and trust_remote_code is on.
    _auto_class = "AutoModelForCausalLM"

    def __init__(self, config):
        super().__init__(config)
        if getattr(config, "mlp_bias", False):
            self._replace_mlp_modules(config)

    # ------------------------------------------------------------------
    # Internal helpers
    # ------------------------------------------------------------------

    def _replace_mlp_modules(self, config) -> None:
        """Swap original MLP instances for RacePerturbedMLP instances.

        This is called **inside** ``__init__`` *after* the parent has built
        the full transformer, so the replacement must happen before
        ``from_pretrained`` loads weights into the module tree.  We do a
        structural replacement: the new module has the same submodule names
        and parameter shapes but ``down_proj`` has a bias parameter.

        Intentionally uses only standard Python / transformers / PyTorch
        primitives — no ``race.*`` imports — so the generated file is fully
        self-contained at inference time.
        """
        # Locate the inner transformer model: try common attribute names used
        # by HuggingFace causal-LM wrappers (e.g. self.model, self.transformer).
        lm = None
        for attr in ("model", "transformer", "backbone"):
            candidate = getattr(self, attr, None)
            if candidate is not None and hasattr(candidate, "layers"):
                lm = candidate
                break
        if lm is None:
            # Last resort: walk immediate children and pick the first nn.Module
            # that itself has a ``layers`` attribute.
            for child in self.children():
                if hasattr(child, "layers"):
                    lm = child
                    break
        if lm is None:
            return

        # ``layers`` is a ModuleList of decoder blocks.
        decoder_layers = lm.layers

        for layer in decoder_layers:
            mlp = getattr(layer, "mlp", None)
            if mlp is None or not isinstance(mlp, {mlp_class_name}):
                continue
            new_mlp = RacePerturbedMLP(config)
            # Copy weights that exist in both (gate_proj, up_proj, down_proj weights).
            # The bias on down_proj will be filled by the state-dict loader.
            new_mlp.load_state_dict(mlp.state_dict(), strict=False)
            layer.mlp = new_mlp

'''


_CONFIG_IMPORT_WITH_CLASS = "from {config_import} import {config_class_name}"


def materialize_race_perturbed_class(
    model: torch.nn.Module,
    save_path: str,
    *,
    local_modeling_stem: Optional[str] = None,
    local_config_stem: Optional[str] = None,
    config_class_name: Optional[str] = None,
) -> str:
    """Generate ``modeling_race_perturbed.py`` and update ``config.json``.

    Writes a Python source file to *save_path* that defines:

    * ``RacePerturbedMLP`` — drop-in MLP with optional ``down_proj`` bias.
    * ``{Prefix}ForCausalLM`` — thin subclass of the original causal LM.

    Also patches ``model.config`` so that ``auto_map`` and ``architectures``
    point at the generated class.  The caller should call
    ``model.save_pretrained(save_path)`` **after** this function.

    Args:
        model: The (already weight-modified) causal LM instance.
        save_path: Directory where the checkpoint will be saved.
        local_modeling_stem: Stem of a patched local ``modeling_*.py`` file.
            When provided, the generated wrapper imports from that local copy.
            When ``None``, it imports from ``transformers`` directly.
        local_config_stem: Stem of a local ``configuration_*.py`` to import
            the config class from (used when ``config_class_name`` is set).
        config_class_name: Name of the config class to use in the wrapper's
            ``config_class`` attribute.  When ``None`` the original
            ``model.config``'s class is used.

    Returns:
        The name of the generated wrapper class (e.g.
        ``"RacePerturbedQwen3ForCausalLM"``).
    """
    causal_lm_cls = type(model)
    base_causal_lm_class = causal_lm_cls.__name__
    mlp_cls_name = _get_mlp_class_name(model) or "MLP"

    # --- Resolve the inner backbone class name (e.g. "Qwen3Model") ---
    base_model_cls_name = _get_base_model_class_name(model) or (
        base_causal_lm_class.replace("ForCausalLM", "").replace("CausalLM", "")
        + "Model"
    )

    # --- Resolve where to import the base classes from ---
    if local_modeling_stem is not None:
        # A patched local copy lives at <save_path>/<local_modeling_stem>.py
        modeling_import = local_modeling_stem
    else:
        # Import straight from transformers (safe for non-mlp-bias cases too)
        modeling_import = _get_modeling_module_name(model)

    # --- Config class resolution ---
    if config_class_name is None:
        # Derive from the live model config
        config_class_name = type(model.config).__name__
        config_module = type(model.config).__module__
    else:
        # Caller-supplied name; derive module from the live config unless a
        # local stem is provided.
        config_module = (
            local_config_stem
            if local_config_stem is not None
            else type(model.config).__module__
        )

    # --- Generate a unique but deterministic wrapper class name ---
    # Strip common suffixes so "Qwen3ForCausalLM" → "Qwen3"
    prefix = base_causal_lm_class.replace("ForCausalLM", "").replace("CausalLM", "")
    wrapper_class_name = f"RacePerturbed{prefix}ForCausalLM"
    # Base model wrapper: e.g. "RacePerturbedQwen3Model"
    base_model_wrapper_class = f"RacePerturbed{prefix}Model"

    # --- Build the config-import line ---
    config_import_line = _CONFIG_IMPORT_WITH_CLASS.format(
        config_import=config_module,
        config_class_name=config_class_name,
    )
    config_class_expr = config_class_name

    # --- Render the template ---
    source = _PERTURBED_MODULE_TEMPLATE.format(
        base_causal_lm_class=base_causal_lm_class,
        base_model_class=base_model_cls_name,
        base_model_wrapper_class=base_model_wrapper_class,
        mlp_class_name=mlp_cls_name,
        wrapper_class_name=wrapper_class_name,
        modeling_import=modeling_import,
        config_import_line=config_import_line,
        config_class_expr=config_class_expr,
    )

    output_file = os.path.join(save_path, "modeling_race_perturbed.py")
    with open(output_file, "w", encoding="utf-8") as fh:
        fh.write(source)
    logger.info(
        "Written: %s  (ForCausalLM=%s, Model=%s)",
        output_file,
        wrapper_class_name,
        base_model_wrapper_class,
    )

    # --- Patch config so AutoModel / AutoModelForCausalLM resolve to wrappers ---
    # Merge into any existing auto_map instead of overwriting it, so that
    # source models that already define custom AutoConfig / AutoTokenizer
    # mappings do not lose those entries.
    #
    # vLLM's Transformers modeling backend requires BOTH:
    #   auto_map["AutoModel"]            — points at the base model class
    #   auto_map["AutoModelForCausalLM"] — points at the causal-LM wrapper
    # The base model class must have ``_supports_attention_backend = True``
    # for vLLM to use its own attention kernels (see supported_models.md,
    # "Writing custom models").
    auto_map_module = "modeling_race_perturbed"
    existing_auto_map = dict(getattr(model.config, "auto_map", None) or {})
    existing_auto_map["AutoModel"] = f"{auto_map_module}.{base_model_wrapper_class}"
    existing_auto_map["AutoModelForCausalLM"] = (
        f"{auto_map_module}.{wrapper_class_name}"
    )
    model.config.auto_map = existing_auto_map
    model.config.architectures = [wrapper_class_name]
    logger.info(
        "Patched config: architectures=%s, auto_map=%s",
        model.config.architectures,
        model.config.auto_map,
    )

    return wrapper_class_name
